const { chromium } = require(require.resolve('playwright', { paths: ['/Users/wangshanpeng/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules'] }));
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const C = require('../core.js');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1040 }, acceptDownloads: true });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install();
    const readState = () => page.evaluate(() => new Promise((resolve, reject) => {
      const request = indexedDB.open('tijian-offline', 1);
      request.onsuccess = () => { const db = request.result, get = db.transaction('workspace', 'readonly').objectStore('workspace').get('main'); get.onsuccess = () => { resolve(get.result); db.close(); }; get.onerror = () => reject(get.error); };
      request.onerror = () => reject(request.error);
    }));
    const home = async () => page.locator('.mobile-focus-bar [data-action=nav][data-view=home]').click();
    const counts = async ns => { for (let i = 0; i < 3; i++) await page.locator('#exam-count-' + i).fill(String(ns[i])); };
    const answerAt = async i => {
      await page.locator('[data-action=exam-jump][data-index="' + i + '"]').click();
      await page.locator('.number-button.current[data-index="' + i + '"]').waitFor();
    };
    await page.goto(pathToFileURL(path.resolve(__dirname, '../题间·离线刷题.html')).href);
    await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
    await page.locator('.topbar [data-action=import]').click();
    const csv = '题目ID,题型,章节,题目,选项A,选项B,答案,解析\ns1,单选题,测试章/基础,单选甲,甲,乙,A,单选解析\ns2,单选题,测试章/基础,单选乙,甲,乙,B,单选解析\nm1,多选题,测试章/基础,多选甲,甲,乙,A|B,多选解析\nm2,多选题,测试章/基础,多选乙,甲,乙,A|B,多选解析\nb1,判断题,测试章/应用,判断甲,,,正确,判断解析\nb2,判断题,测试章/应用,判断乙,,,错误,判断解析\nout,单选题,其他章,范围外题目,甲,乙,A,不应抽中\n';
    await page.locator('#csv-file').setInputFiles({ name: '模拟考试测试.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
    await page.locator('[data-action=confirm-import]').click();
    await page.waitForFunction(() => document.querySelector('.hero h2')?.textContent === '模拟考试测试');
    await page.locator('[data-action=mode][data-mode=sequential]').click();
    await page.locator('[data-action=choose][data-label=A]').click();
    await page.locator('.answer-panel.good').waitFor();
    const before = await readState();
    await home();
    await page.locator('[data-action=mode][data-mode=exam]').click();
    await page.locator('#exam-chapter').selectOption('测试章');
    await counts([3, 1, 1]); assert(await page.locator('[data-action=exam-start]').isDisabled());
    await counts([0, 0, 0]); assert(await page.locator('[data-action=exam-start]').isDisabled());
    await counts([1, 1, 1]);
    await page.locator('#exam-duration').fill('0'); assert(await page.locator('[data-action=exam-start]').isDisabled());
    await page.locator('#exam-duration').fill('60');
    await page.screenshot({ path: '/tmp/tijian-exam-config.png', fullPage: true });
    await page.locator('[data-action=exam-start]').click();
    await page.locator('.mobile-focus-bar .exam-clock').waitFor();
    assert(!await page.locator('.sidebar').isVisible()); assert(!await page.locator('.topbar').isVisible());
    assert.equal(await page.locator('.number-button').count(), 3);
    for (let i = 0; i < 3; i++) {
      await answerAt(i);
      const type = await page.locator('.question-labels .chip').innerText();
      if (type === '判断题') continue;
      const text = await page.locator('.question-text').innerText();
      await page.locator('[data-action=exam-choose][data-label=' + (type === '单选题' && text === '单选乙' ? 'B' : 'A') + ']').click();
      await page.waitForFunction(() => !!document.querySelector('.option.selected'));
      if (type === '单选题') {
        await page.locator('[data-action=exam-clear]').click();
        await page.waitForFunction(() => !document.querySelector('.option.selected'));
        await page.locator('[data-action=exam-choose][data-label=' + (text === '单选乙' ? 'B' : 'A') + ']').click();
      } else await page.locator('[data-action=exam-mark]').click();
      assert.equal(await page.locator('.answer-panel, .option.correct, .option.incorrect, .history-right, .history-wrong').count(), 0);
    }
    let saved = await readState();
    assert.deepEqual(saved.records, before.records, 'exam does not grade before submission');
    assert.deepEqual(saved.session, before.session, 'exam preserves ordinary practice');
    assert(saved.activeExam.questions.every(q => q.chapter.startsWith('测试章/')));
    assert.equal(new Set(saved.activeExam.questions.map(q => q.id)).size, 3);
    const deadline = saved.activeExam.deadline, answers = saved.activeExam.answers;
    await page.screenshot({ path: '/tmp/tijian-exam-focus.png', fullPage: true });
    await page.reload();
    await page.locator('[data-action=exam-resume]').click();
    await page.locator('.mobile-focus-bar .exam-clock').waitFor();
    saved = await readState();
    assert.equal(saved.activeExam.deadline, deadline); assert.deepEqual(saved.activeExam.answers, answers);
    assert.equal(await page.locator('.number-button.exam-marked').count(), 1);
    console.log('PASS: configurable scoped exam, hidden answers, editable responses, focus mode and reload recovery');

    await page.locator('.answer-card [data-action=exam-submit]').click();
    await page.getByRole('heading', { name: '确认交卷？', exact: true }).waitFor();
    await page.locator('[data-action=confirm]').click();
    await page.getByRole('heading', { name: '考试成绩', exact: true }).waitFor();
    assert.equal(await page.locator('.exam-score').innerText(), '33.3/ 100');
    saved = await readState();
    assert.equal(saved.activeExam, null); assert.equal(saved.exams.length, 1);
    assert.equal(C.examResult(saved.exams[0]).unanswered, 1);
    const multi = saved.exams[0].questions.find(q => q.type === '多选题'), judge = saved.exams[0].questions.find(q => q.type === '判断题');
    assert(saved.records[saved.exams[0].bankId + '/' + multi.id].inWrong);
    assert(saved.records[saved.exams[0].bankId + '/' + judge.id].inWrong);
    assert.equal(saved.records[saved.exams[0].bankId + '/' + judge.id].attempts, 0);
    const gradedRecords = saved.records;
    await page.locator('[data-action=exam-review][data-filter=wrong]').click();
    await page.locator('.answer-panel.bad').waitFor();
    assert.equal(await page.locator('.number-button').count(), 2);
    await page.locator('#exam-review-filter').selectOption('unanswered');
    assert.equal(await page.locator('.number-button').count(), 1);
    assert.match(await page.locator('.answer-panel').innerText(), /你的答案：未作答/);
    await page.screenshot({ path: '/tmp/tijian-exam-review.png', fullPage: true });
    await page.locator('.focus-actions [data-action=exam-result]').click();
    await page.screenshot({ path: '/tmp/tijian-exam-result.png', fullPage: true });
    await page.reload();
    await page.locator('.sidebar [data-action=nav][data-view=exams]').click();
    assert.equal(await page.locator('.exam-history .data-card').count(), 1);
    assert.deepEqual((await readState()).records, gradedRecords, 'review/reload cannot grade twice');
    console.log('PASS: unified scoring, unanswered handling, wrong collection, review filters and durable history');

    await page.locator('.sidebar [data-action=nav][data-view=manage]').click();
    const downloadPromise = page.waitForEvent('download');
    await page.locator('[data-action=export-backup]').click();
    const download = await downloadPromise, backupPath = '/tmp/tijian-exam-backup.json';
    await download.saveAs(backupPath);
    assert.equal(C.validateState(JSON.parse(fs.readFileSync(backupPath, 'utf8'))).exams.length, 1);
    await page.locator('#backup-file').setInputFiles(backupPath);
    await page.getByRole('heading', { name: '恢复备份 · 将替换当前全部数据' }).waitFor();
    await page.locator('[data-action=confirm]').click();
    await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
    assert.equal((await readState()).exams.length, 1);
    assert.deepEqual((await readState()).session, before.session);
    await page.locator('[data-action=continue]').click();
    await page.locator('.answer-panel.good').waitFor();
    await home();
    console.log('PASS: exam backup restore and ordinary practice remain compatible');

    await page.locator('[data-action=mode][data-mode=exam]').click();
    await counts([0, 0, 1]); await page.locator('#exam-duration').fill('1');
    await page.locator('[data-action=exam-start]').click();
    await page.locator('.mobile-focus-bar .exam-clock').waitFor();
    const originalDeadline = (await readState()).activeExam.deadline;
    await home();
    await page.clock.fastForward(30000);
    await page.reload();
    await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
    assert.equal((await readState()).activeExam.deadline, originalDeadline);
    await page.clock.fastForward(31000);
    await page.getByRole('heading', { name: '考试成绩', exact: true }).waitFor();
    saved = await readState();
    assert.equal(saved.activeExam, null); assert.equal(saved.exams.length, 2);
    assert(saved.exams[0].autoSubmitted); assert.equal(C.examResult(saved.exams[0]).score, 0);
    await page.clock.fastForward(10000);
    assert.equal((await readState()).exams.length, 2);
    await page.locator('.exam-result-actions [data-action=nav][data-view=home]').click();
    await page.locator('[data-action=mode][data-mode=exam]').click();
    await counts([1, 0, 0]); await page.locator('#exam-duration').fill('1');
    await page.locator('[data-action=exam-start]').click();
    await page.locator('.mobile-focus-bar .exam-clock').waitFor();
    assert(C.validateState(await readState()).activeExam, 'active exam can be backed up');
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.setViewportSize({ width: 1440, height: 1040 });
    // Simulate a closed page: no app timer runs while this document is unloaded.
    await page.goto('about:blank');
    await page.clock.fastForward(61000);
    await page.goto(pathToFileURL(path.resolve(__dirname, '../题间·离线刷题.html')).href);
    await page.getByRole('heading', { name: '考试成绩', exact: true }).waitFor();
    saved = await readState();
    assert.equal(saved.activeExam, null); assert.equal(saved.exams.length, 3); assert(saved.exams[0].autoSubmitted);
    assert.deepEqual(errors, []);
    console.log('PASS: countdown survives leaving, reload and a closed page; expiration submits exactly once');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
