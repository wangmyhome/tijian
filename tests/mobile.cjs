const { chromium, webkit, devices } = require(require.resolve('playwright', { paths: ['/Users/wangshanpeng/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules'] }));
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

(async () => {
  const useWebkit = process.env.MOBILE_BROWSER === 'webkit';
  const browser = await (useWebkit ? webkit : chromium).launch({ headless: true, ...(useWebkit ? {} : { channel: 'chrome' }) });
  try {
    const context = await browser.newContext({ serviceWorkers: 'block', ...devices['iPhone 13'], acceptDownloads: true });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await context.route('**/config.js', route => route.fulfill({ contentType: 'application/javascript', body: 'window.TIJIAN_CLOUD_CONFIG = { enabled: false };' }));
    const file = pathToFileURL(path.resolve(__dirname, '../题间·离线刷题.html')).href;
    const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile page must fit viewport');
    const nav = view => page.locator('.mobile-nav [data-view=' + view + ']').tap();
    const openCard = async () => { await page.locator('.mobile-reading-settings').tap(); await page.locator('[data-action=settings-card]').tap(); await page.locator('.answer-sheet-open .answer-card').waitFor(); };
    const back = async () => page.locator('.mobile-focus-bar>[data-action=nav]').tap();
    await page.goto(process.env.MOBILE_URL || file);
    await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
    assert(!await page.locator('.sidebar').isVisible());
    assert(await page.locator('.mobile-nav').isVisible());
    for (const size of [{ width: 320, height: 568 }, { width: 375, height: 667 }, { width: 390, height: 844 }, { width: 430, height: 932 }, { width: 844, height: 390 }]) {
      await page.setViewportSize(size); await noOverflow();
      assert(await page.locator('.mobile-nav').isVisible());
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/tijian-mobile-home.png', scale: 'css' });
    await nav('more');
    await page.locator('.more-links [data-view=manage]').tap();
    await page.getByRole('heading', { name: '数据与备份', exact: true }).waitFor();
    assert(await page.locator('[data-action=export-backup]').isVisible());
    await nav('home');
    await page.locator('.topbar [data-action=import]').tap();
    await page.locator('#csv-file').setInputFiles(path.resolve(__dirname, '../../题库导入模板.csv'));
    await page.locator('[data-action=confirm-import]').waitFor();
    await noOverflow();
    await page.locator('#import-name').fill('手机导入题库');
    await page.locator('[data-action=confirm-import]').tap();
    await page.waitForFunction(() => document.querySelector('.hero h2')?.textContent === '手机导入题库');
    await page.locator('#home-bank').selectOption('builtin-theory');
    await page.waitForFunction(() => document.querySelector('.hero h2')?.textContent.includes('三级'));
    await nav('more');
    await page.locator('.more-links [data-action=settings]').tap();
    await page.getByRole('heading', { name: '刷题设置', exact: true }).waitFor();
    await noOverflow();
    assert.equal(await page.locator('.theme-choice').count(), 8);
    await page.locator('[data-action=setting-theme][data-value=classic-eye]').tap();
    await page.waitForFunction(() => document.body.dataset.theme === 'classic-eye');
    await page.locator('.modal-footer [data-action=close-modal]').tap();
    await nav('home');
    console.log('PASS: iPhone navigation, CSV import, backup access, themes and portrait/landscape layouts');

    await page.locator('[data-action=mode][data-mode=sequential]').tap();
    await page.locator('.question-card').waitFor();
    assert(!await page.locator('.mobile-nav').isVisible());
    assert(!await page.locator('.topbar').isVisible());
    assert(!await page.locator('.practice-aside').isVisible());
    assert(await page.locator('.mobile-focus-bar').isVisible());
    const footer = await page.locator('.question-tools').boundingBox();
    assert(footer.y + footer.height <= 845 && footer.y + footer.height >= 843);
    for (const letter of ['A', 'B', 'D']) await page.locator('[data-action=choose][data-label=' + letter + ']').tap();
    await page.locator('.question-footer [data-action=submit]').tap();
    await page.locator('.answer-panel.good').waitFor();
    await noOverflow();
    await page.screenshot({ path: '/tmp/tijian-mobile-answer.png', scale: 'css' });
    await page.locator('[data-action=favorite]').tap();
    await page.locator('[data-action=toggle-note]').tap();
    await page.locator('#question-note').fill('手机端记录的笔记');
    await page.waitForFunction(() => document.querySelector('#note-status')?.textContent === '已保存');
    assert(!await page.locator('.question-footer').isVisible());
    await page.locator('[data-action=note-done]').tap();
    assert(await page.locator('.question-tools').isVisible());
    await openCard();
    assert.equal(await page.locator('.practice-aside').getAttribute('role'), 'dialog');
    assert(await page.locator('.question-card').evaluate(el => el.inert));
    await page.screenshot({ path: '/tmp/tijian-mobile-answer-card.png', scale: 'css' });
    await page.locator('[data-action=jump][data-index="1"]').tap();
    await page.waitForFunction(() => document.querySelector('.question-count strong')?.textContent === '2');
    assert(!await page.locator('.practice-aside').isVisible());
    assert(!await page.locator('.question-card').evaluate(el => el.inert));
    await noOverflow();
    await page.reload();
    await page.locator('[data-action=continue]').tap();
    await page.waitForFunction(() => document.querySelector('.question-count strong')?.textContent === '2');
    await openCard(); await page.locator('[data-action=jump][data-index="0"]').tap();
    await page.locator('.answer-panel.good').waitFor();
    assert.equal(await page.locator('#question-note').inputValue(), '手机端记录的笔记');
    await back();
    console.log('PASS: touch answers, fixed controls, notes, answer sheet, jump and persisted progress');

    await nav('favorite');
    assert.equal(await page.locator('.question-item').count(), 1);
    await nav('exams');
    await page.locator('[data-action=exam-config]').tap();
    for (let i = 0; i < 3; i++) await page.locator('#exam-count-' + i).fill(i ? '0' : '2');
    await noOverflow();
    await page.locator('[data-action=exam-start]').tap();
    await page.locator('.mobile-focus-bar .exam-clock').waitFor();
    assert(!await page.locator('.practice-aside').isVisible());
    await page.locator('[data-action=exam-choose][data-label=A]').tap();
    assert.equal(await page.locator('.answer-panel').count(), 0);
    await page.screenshot({ path: '/tmp/tijian-mobile-exam.png', scale: 'css' });
    await openCard();
    assert.equal(await page.locator('.exam-clock').count(), 2);
    await page.locator('.answer-card [data-action=exam-submit]').tap();
    assert(!await page.locator('.practice-aside').isVisible());
    await page.getByRole('heading', { name: '确认交卷？', exact: true }).waitFor();
    await page.locator('[data-action=confirm]').tap();
    await page.getByRole('heading', { name: '考试成绩', exact: true }).waitFor();
    await noOverflow();
    await page.locator('[data-action=exam-review][data-filter=""]').tap();
    await page.locator('.answer-panel').waitFor();
    await openCard();
    await page.locator('.mobile-sheet-dismiss').tap();
    assert(!await page.locator('.practice-aside').isVisible());
    assert.deepEqual(errors, []);
    console.log('PASS: mobile timed exam, submission, results and review sheet');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
