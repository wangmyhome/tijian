const { chromium, webkit } = require(require.resolve('playwright', { paths: ['/Users/wangshanpeng/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules'] }));
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1040 }, colorScheme: 'light', acceptDownloads: true });
  const page = await context.newPage();
  const nav = async view => {
    if (await page.locator('body.focus-mode').count()) await page.locator('.mobile-focus-bar [data-action=nav][data-view=home]').click();
    if (view !== 'home' || !await page.getByRole('heading', { name: '我的题库', exact: true }).count()) await page.locator('.sidebar [data-action=nav][data-view=' + view + ']').click();
  };
  const errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()); });
  const file = pathToFileURL(path.resolve(__dirname, '../题间·离线刷题.html')).href;
  await page.goto(file);
  await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
  assert(await page.locator('.hero').innerText().then(t => t.includes('1,751')));
  await page.screenshot({ path: '/tmp/tijian-home.png', fullPage: true });
  console.log('PASS: offline boot with all 1751 original questions');

  await page.locator('[data-action=mode][data-mode=sequential]').click();
  await page.locator('.question-card').waitFor();
  assert.equal(await page.locator('.options .option').count(), 5);
  await page.locator('[data-action=choose][data-label=A]').click();
  await page.locator('[data-action=choose][data-label=B]').click();
  await page.locator('[data-action=choose][data-label=D]').click();
  await page.locator('[data-action=submit]').click();
  await page.locator('.answer-panel.good').waitFor();
  await page.locator('[data-action=favorite]').click();
  await page.locator('[data-action=toggle-note]').click();
  await page.locator('#question-note').fill('这是一条保存后可恢复的笔记。');
  await page.waitForFunction(() => document.querySelector('#note-status')?.textContent === '已保存');
  await page.screenshot({ path: '/tmp/tijian-practice.png', fullPage: true });
  await page.locator('[data-action=next]').click();
  await page.waitForFunction(() => document.querySelector('.question-count strong')?.textContent === '2');
  await page.reload();
  await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
  await page.locator('[data-action=continue]').click();
  assert.equal(await page.locator('.question-count strong').innerText(), '2');
  await page.locator('[data-action=previous]').click();
  await page.locator('.answer-panel.good').waitFor();
  assert.equal(await page.locator('#question-note').inputValue(), '这是一条保存后可恢复的笔记。');
  assert(await page.locator('[data-action=favorite]').innerText().then(t => t.includes('已收藏')));
  console.log('PASS: multi-select exact grading, favorite, note and reload resume');

  await page.locator('[data-action=next]').click();
  await page.locator('[data-action=choose][data-label=E]').click();
  await page.locator('[data-action=submit]').click();
  await page.locator('.answer-panel.bad').waitFor();
  await nav('wrong');
  assert.equal(await page.locator('.question-item').count(), 1);
  await page.locator('[data-action=list-remove-wrong]').click();
  await page.locator('[data-action=confirm]').click();
  await page.locator('.empty').waitFor();
  console.log('PASS: wrong answers collect automatically and remove with confirmation');

  await nav('home');
  await page.locator('.topbar [data-action=import]').click();
  await page.locator('#csv-file').setInputFiles(path.resolve(__dirname, '../../题库导入模板.csv'));
  await page.locator('[data-action=confirm-import]').waitFor();
  await page.locator('#import-name').fill('七选项测试题库');
  await page.locator('[data-action=edit-import][data-index="0"]').click();
  await page.locator('#edit-analysis').fill('导入前修改的解析。');
  await page.locator('[data-action=save-edit]').click();
  await page.locator('[data-action=confirm-import]').click();
  await page.waitForFunction(() => document.querySelector('.hero h2')?.textContent === '七选项测试题库');
  await page.locator('[data-action=mode][data-mode=multiple]').click();
  if (await page.locator('[data-action=confirm]').isVisible()) await page.locator('[data-action=confirm]').click();
  await page.waitForFunction(() => document.querySelectorAll('.option').length === 7);
  for (const letter of ['G', 'F', 'E', 'D', 'C', 'B', 'A']) await page.locator('[data-action=choose][data-label=' + letter + ']').click();
  await page.locator('[data-action=submit]').click();
  await page.locator('.answer-panel.good').waitFor();
  console.log('PASS: CSV preview/edit/import, type filtering and unordered seven-option answer');

  await nav('home');
  await page.locator('[data-action=mode][data-mode=judgment]').click();
  await page.locator('[data-action=choose][data-label=A]').click();
  await page.locator('.answer-panel.good').waitFor();
  console.log('PASS: true/false immediate grading');

  await nav('manage');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('[data-action=export-backup]').click();
  const download = await downloadPromise;
  const backupPath = '/tmp/tijian-test-backup.json';
  await download.saveAs(backupPath);
  const backup = JSON.parse(fs.readFileSync(backupPath, 'utf8'));
  assert.equal(backup.banks.length, 2);
  assert.equal(backup.banks[1].questions.length, 3);
  assert(Object.values(backup.records).some(r => r.note.includes('可恢复')));
  await page.locator('#backup-file').setInputFiles(backupPath);
  await page.getByRole('heading', { name: '恢复备份 · 将替换当前全部数据' }).waitFor();
  await page.locator('[data-action=confirm]').click();
  await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: '我的题库', exact: true }).waitFor();
  assert.equal(await page.locator('.bank-row').count(), 2);
  console.log('PASS: complete backup export, restore and persisted recovery');

  await page.locator('[data-action=mode][data-mode=random]').click();
  assert((await page.locator('#mode-chapter option').count()) >= 3);
  await page.locator('#mode-chapter').selectOption('第二章');
  await page.locator('[data-action=start-configured]').click();
  await page.locator('.question-card').waitFor();
  assert.equal(await page.locator('.question-count').innerText().then(s => s.replace(/\s+/g, '')), '1/2');
  console.log('PASS: hierarchical chapter filtering');

  await nav('home');
  await page.locator('[data-action=mode][data-mode=single]').click();
  await page.locator('[data-action=confirm]').click();
  await page.locator('.question-card').waitFor();
  await page.keyboard.press('B');
  await page.locator('.answer-panel.good').waitFor();
  assert(await page.locator('.analysis').innerText().then(t => t.includes('导入前修改的解析')));
  console.log('PASS: single-choice immediate grading and keyboard selection');

  await nav('home');
  await page.locator('.topbar [data-action=import]').click();
  const invalidCSV = '题型,题目,选项A,选项B,答案\n单选题,"<img src=x onerror=alert(1)>",甲,乙,A\n单选题,无效答案,甲,乙,G\n';
  await page.locator('#csv-file').setInputFiles({ name: 'validation.csv', mimeType: 'text/csv', buffer: Buffer.from(invalidCSV) });
  await page.locator('[data-action=confirm-import]').waitFor();
  assert(await page.locator('[data-action=confirm-import]').isDisabled());
  assert.equal(await page.locator('.preview-table img').count(), 0);
  await page.locator('[data-action=edit-import][data-index="1"]').click();
  await page.locator('#edit-answer').fill('B');
  await page.locator('[data-action=save-edit]').click();
  assert(await page.locator('[data-action=confirm-import]').isEnabled());
  await page.locator('[data-action=close-modal]').first().click();
  console.log('PASS: invalid CSV blocks import, editor repairs errors, HTML in questions is escaped');

  await nav('home');
  await page.locator('[data-action=mode][data-mode=random]').click();
  await page.locator('#mode-count').fill('2');
  await page.locator('[data-action=start-configured]').click();
  await page.locator('.question-card').waitFor();
  const randomFirst = await page.locator('.question-text').innerText();
  assert.equal(await page.locator('.question-count').innerText().then(s => s.replace(/\s+/g, '')), '1/2');
  await page.locator('[data-action=next]').click();
  await page.waitForFunction(() => document.querySelector('.question-count strong')?.textContent === '2');
  const randomSecond = await page.locator('.question-text').innerText();
  assert.notEqual(randomFirst, randomSecond);
  await page.reload();
  await page.locator('[data-action=continue]').waitFor();
  await page.locator('[data-action=continue]').click();
  assert.equal(await page.locator('.question-text').innerText(), randomSecond);
  console.log('PASS: random questions do not repeat and order survives reload');

  await nav('home');
  await page.locator('.topbar [data-action=settings]').click();
  await page.locator('[data-action=setting-theme][data-value=dark]').click();
  await page.waitForFunction(() => document.body.dataset.theme === 'dark');
  assert.equal(await page.locator('body').getAttribute('data-theme'), 'dark');
  await page.locator('[data-action=setting-font][data-value="23"]').click();
  await page.waitForFunction(() => getComputedStyle(document.documentElement).getPropertyValue('--font') === '23px');
  await page.locator('[data-action=close-modal]').last().click();
  await page.locator('[data-action=continue]').click();
  assert.equal(await page.locator('.question-text').evaluate(x => getComputedStyle(x).fontSize), '23px');
  await page.screenshot({ path: '/tmp/tijian-dark.png', fullPage: true });
  console.log('PASS: theme and font settings');

  assert.equal(requests.length, 0, 'app must not make external network requests');
  assert.deepEqual(errors, [], 'no uncaught browser errors');
  console.log('PASS: no external network requests or browser errors');
  await context.close();
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
